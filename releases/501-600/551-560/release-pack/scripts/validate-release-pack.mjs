import { readdir, readFile, stat } from "node:fs/promises";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const required = ["src/index.ts", "policies/safety-defaults.json", "policies/release-gates.json", "policies/decision-integrity.json", "openapi/releases-551-560.yaml", "architecture/HLD.md", "architecture/LLD.md", "architecture/TRUST_BOUNDARIES.md", "architecture/NON_FUNCTIONAL_REQUIREMENTS.md", "architecture/SECURITY_ARCHITECTURE.md", "architecture/PRIVACY_ARCHITECTURE.md", "architecture/RESILIENCE_ARCHITECTURE.md", "evidence/GO_NO_GO_TEMPLATE.md", "evidence/DECISION_RECORD_TEMPLATE.md", "runbooks/THREAT_MODEL.md", "runbooks/ROLLBACK.md", "runbooks/DECISION_APPEAL.md", "docs/RELEASE_551_UNIFIED_WORK_QUEUE_AND_PERSONAL_PRODUCTIVITY.md", "docs/RELEASE_552_EMAIL_AND_CALENDAR_AUTOMATION_SAFETY.md", "docs/RELEASE_553_MEETING_INTELLIGENCE_AND_CONSENT.md", "docs/RELEASE_554_DOCUMENT_COLLABORATION_AND_VERSION_CONTROL.md", "docs/RELEASE_555_ENTERPRISE_SEARCH_AND_KNOWLEDGE_ASSISTANCE.md", "docs/RELEASE_556_TASK_DELEGATION_AND_APPROVAL_OPERATIONS.md", "docs/RELEASE_557_OFFICE_PROCESS_ANALYTICS_WITHOUT_SURVEILLANCE.md", "docs/RELEASE_558_KNOWLEDGE_WORKER_ACCESSIBILITY_AND_INCLUSION.md", "docs/RELEASE_559_WORKPLACE_CHANGE_AND_ADOPTION.md", "docs/RELEASE_560_WORKPLACE_OPERATIONS_ASSURANCE_GATE.md", "schemas/release-551.schema.json", "schemas/release-552.schema.json", "schemas/release-553.schema.json", "schemas/release-554.schema.json", "schemas/release-555.schema.json", "schemas/release-556.schema.json", "schemas/release-557.schema.json", "schemas/release-558.schema.json", "schemas/release-559.schema.json", "schemas/release-560.schema.json"];

async function exists(path) {
  try { return (await stat(join(root, path))).isFile(); }
  catch { return false; }
}

for (const path of required) {
  if (!await exists(path)) throw new Error(`Missing required file: ${path}`);
}

async function walk(directory) {
  const output = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) output.push(...await walk(path));
    else output.push(path);
  }
  return output;
}

const files = await walk(root);
const forbidden = [
  /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/,
  /ghp_[A-Za-z0-9]{30,}/,
  /sk-[A-Za-z0-9]{20,}/
];

for (const file of files) {
  const text = await readFile(file, "utf8").catch(() => null);
  if (text === null) continue;
  const selfTest = file.endsWith("redaction.ts") || file.endsWith("validate-release-pack.mjs");
  for (const pattern of forbidden) {
    if (!selfTest && pattern.test(text)) throw new Error(`Secret-shaped content in ${relative(root,file)}`);
  }
}

const counts = {
  migrations: files.filter(file => file.includes("/migrations/") && file.endsWith(".sql")).length,
  documents: files.filter(file => file.includes("/docs/") && file.endsWith(".md")).length,
  schemas: files.filter(file => file.includes("/schemas/") && file.endsWith(".json")).length,
  releaseContracts: files.filter(file => /\/release\d+\/contracts\.ts$/.test(file)).length,
  releasePolicies: files.filter(file => /\/release\d+\/policy\.ts$/.test(file)).length,
  releaseServices: files.filter(file => /\/release\d+\/service\.ts$/.test(file)).length
};

for (const [name,count] of Object.entries(counts)) {
  if (count !== 10) throw new Error(`Expected 10 ${name}, found ${count}`);
}

console.log(`Release pack validation passed: ${files.length} files`);
